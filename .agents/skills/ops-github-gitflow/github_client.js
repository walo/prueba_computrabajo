/**
 * GitHub API Client for Automation Workflows (Pull Requests & Repositories)
 * Zero external dependencies - uses native Node.js 'https' and 'child_process'
 */
const https = require('https');
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// Load .env manually if present
function loadEnv() {
  const envPath = path.resolve(process.cwd(), '.env');
  if (!fs.existsSync(envPath)) return {};
  const lines = fs.readFileSync(envPath, 'utf8').split('\n');
  const env = {};
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.substring(0, eqIdx).trim();
      const val = trimmed.substring(eqIdx + 1).trim().replace(/(^["']|["']$)/g, '');
      env[key] = val;
    }
  }
  return env;
}

const envVars = loadEnv();
const GITHUB_TOKEN = process.env.GITHUB_TOKEN || envVars.GITHUB_TOKEN;

function getRepoInfo() {
  try {
    const remoteUrl = execSync('git config --get remote.origin.url', { encoding: 'utf8' }).trim();
    const match = remoteUrl.match(/github\.com[:/](.+?)\/(.+?)(\.git)?$/);
    if (match) {
      return { owner: match[1], repo: match[2] };
    }
  } catch {
    // fallback
  }
  return { owner: null, repo: null };
}


function getCurrentBranch() {
  try {
    return execSync('git rev-parse --abbrev-ref HEAD', { encoding: 'utf8' }).trim();
  } catch {
    return null;
  }
}

function githubRequest(method, endpoint, body) {
  return new Promise((resolve, reject) => {
    if (!GITHUB_TOKEN) {
      return reject(new Error('GITHUB_TOKEN not found in environment or .env file.'));
    }

    const payload = body ? JSON.stringify(body) : null;
    const options = {
      hostname: 'api.github.com',
      port: 443,
      path: endpoint,
      method: method,
      headers: {
        'Accept': 'application/vnd.github+json',
        'Authorization': `Bearer ${GITHUB_TOKEN}`,
        'User-Agent': 'Acciona-Enterprise-GitFlow-Automation',
        'X-GitHub-Api-Version': '2022-11-28'
      }
    };

    if (payload) {
      options.headers['Content-Type'] = 'application/json';
      options.headers['Content-Length'] = Buffer.byteLength(payload);
    }

    const req = https.request(options, (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        let parsed;
        try {
          parsed = data ? JSON.parse(data) : {};
        } catch {
          parsed = { raw: data };
        }

        if (res.statusCode >= 200 && res.statusCode < 300) {
          resolve({ status: res.statusCode, data: parsed });
        } else {
          const err = new Error(parsed.message || `GitHub API error ${res.statusCode}`);
          err.status = res.statusCode;
          err.data = parsed;
          reject(err);
        }
      });
    });

    req.on('error', (err) => reject(err));
    if (payload) req.write(payload);
    req.end();
  });
}

async function createPR(headBranch, title, baseBranch = 'develop', bodyText = '') {
  const { owner, repo } = getRepoInfo();
  if (!owner || !repo) {
    console.error('Error: Could not determine GitHub repository from git remote origin.');
    process.exit(1);
  }

  const branch = headBranch || getCurrentBranch();
  if (!branch || branch === 'develop' || branch === 'main' || branch === 'master') {
    console.error(`Error: Cannot create PR from protected branch '${branch}'.`);
    process.exit(1);
  }

  const targetBase = baseBranch || 'develop';
  const prTitle = title || `feat: merge ${branch} into ${targetBase}`;
  const prBody = bodyText || `Automated PR generated by /ship workflow for branch \`${branch}\`.`;

  const fallbackUrl = `https://github.com/${owner}/${repo}/compare/${targetBase}...${branch}?expand=1`;

  if (!GITHUB_TOKEN) {
    console.log(`\n⚠️  GITHUB_TOKEN is not configured in .env or environment.`);
    console.log(`🔗 Create the PR manually at:\n${fallbackUrl}\n`);
    console.log(`💡 To automate PR creation, add GITHUB_TOKEN=ghp_xxx to your .env file.`);
    return;
  }

  try {
    const res = await githubRequest('POST', `/repos/${owner}/${repo}/pulls`, {
      title: prTitle,
      head: branch,
      base: targetBase,
      body: prBody,
      draft: false
    });

    console.log(`\n🎉 Pull Request created successfully!`);
    console.log(`📌 PR #${res.data.number}: ${res.data.title}`);
    console.log(`🎯 Base branch: ${targetBase}`);
    console.log(`🔗 URL: ${res.data.html_url}\n`);
  } catch (error) {
    if (error.status === 422 && error.data && error.data.errors) {
      const alreadyExists = error.data.errors.some(e => /already exists/i.test(e.message || ''));
      if (alreadyExists) {
        console.log(`\nℹ️  A Pull Request already exists for branch '${branch}'.`);
        console.log(`🔗 Check repository PRs at: https://github.com/${owner}/${repo}/pulls\n`);
        return;
      }
    }
    console.error(`\n❌ Error creating Pull Request: ${error.message}`);
    console.log(`🔗 Manual URL fallback:\n${fallbackUrl}\n`);
  }
}

async function updatePRBase(prNumber, newBase = 'develop') {
  const { owner, repo } = getRepoInfo();
  if (!owner || !repo) {
    console.error('Error: Could not determine GitHub repository from git remote origin.');
    process.exit(1);
  }

  if (!prNumber) {
    console.error('Error: PR number is required.');
    process.exit(1);
  }

  try {
    const res = await githubRequest('PATCH', `/repos/${owner}/${repo}/pulls/${prNumber}`, {
      base: newBase
    });

    console.log(`\n🎉 Pull Request #${prNumber} base branch updated!`);
    console.log(`🎯 New base branch: ${res.data.base.ref}`);
    console.log(`🔗 URL: ${res.data.html_url}\n`);
  } catch (error) {
    console.error(`\n❌ Error updating Pull Request #${prNumber}: ${error.message}`);
  }
}

// CLI Routing
const [,, command, ...args] = process.argv;

if (!command || command === 'help') {
  console.log(`
Usage: node github_client.js <command> [arguments]

Commands:
  create-pr [headBranch] [title] [baseBranch] [body]
      Creates a Pull Request on GitHub.
      Default baseBranch is 'develop'.

  update-pr-base <prNumber> [newBase]
      Updates the target base branch of an existing Pull Request.
      Default newBase is 'develop'.
  `);
  process.exit(0);
}

if (command === 'create-pr') {
  const [headBranch, title, baseBranch, body] = args;
  createPR(headBranch, title, baseBranch || 'develop', body);
} else if (command === 'update-pr-base') {
  const [prNumber, newBase] = args;
  updatePRBase(prNumber, newBase || 'develop');
} else {
  console.error(`Unknown command '${command}'. Use 'node github_client.js help' for usage.`);
  process.exit(1);
}
